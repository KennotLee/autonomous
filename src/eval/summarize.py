"""Build outputs/metrics/test_set_summary.md (model vs baseline on the 2025 test set) from the comparison CSVs.

Usage: python src/eval/summarize.py
Inputs: outputs/metrics/aar_model_vs_baseline.csv (evaluate_aar.py),
        outputs/metrics/delay_model_vs_baseline_*.csv (evaluate_delay.py),
        outputs/metrics/leakage_hub_state.csv (leakage_checks.py).
"""
import pandas as pd

from baselines import OUT


def fmt_ci(lo, hi):
    return f"[{lo:+.3f}, {hi:+.3f}]"


def aar_table():
    df = pd.read_csv(OUT / "aar_model_vs_baseline.csv")
    lines = ["| slice | icao | h | hours | model RMSE | schedule baseline | hour-of-week mean | persistence "
             "| vs schedule | vs hour-of-week | 90% CI RMSE diff vs schedule |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in df.itertuples():
        lines.append(f"| {r.slice} | {r.icao} | {r.h} | {r.n_hours} | **{r.rmse_model:.3f}** | {r.rmse_scheduled_x_ratio:.3f} "
                     f"| {r.rmse_hour_of_week_mean:.3f} | {r.rmse_persistence:.3f} | {-r.impr_vs_scheduled_x_ratio_pct:+.1f}% "
                     f"| {-r.impr_vs_hour_of_week_mean_pct:+.1f}% | {fmt_ci(r.diff_vs_sched_ci90_lo, r.diff_vs_sched_ci90_hi)} |")
    return "\n".join(lines)


def delay_table(path):
    df = pd.read_csv(path)
    lines = ["| h | slice | flights | late | model PR-AUC | best baseline PR-AUC | global rate | vs best baseline "
             "| 90% CI PR-AUC diff | model Brier | baseline Brier |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in df.itertuples():
        lines.append(f"| {r.h} | {r.slice} | {r.n} | {r.positives} | **{r.pr_auc_model:.3f}** "
                     f"| {r.pr_auc_base_rate_origin_dephour_month:.3f} | {r.pr_auc_base_rate:.3f} "
                     f"| {r.pr_auc_impr_vs_best_pct:+.1f}% | {fmt_ci(r.diff_vs_best_ci90_lo, r.diff_vs_best_ci90_hi)} "
                     f"| {r.brier_model:.3f} | {r.brier_base_rate_origin_dephour_month:.3f} |")
    return "\n".join(lines)


def main():
    parts = ["# Model vs baseline on the 2025 test set (generated by src/eval/summarize.py; do not edit by hand)\n",
             "Test = 2025-01-01 UTC onward; all baselines fit on data before 2025 only. CIs: 90% bootstrap "
             "(AAR: whole days resampled; delay: flights resampled). Negative RMSE change = model better.\n",
             "## Hourly arrivals (AAR proxy): P2 LightGBM vs P4 baselines\n",
             "Caveat: arr_count comes from a ~0.5% BTS sample (0 in ~82% of hours). This compares models on this "
             "target; it is not real runway-capacity accuracy.\n", aar_table(), ""]
    for path in sorted(OUT.glob("delay_model_vs_baseline_*.csv")):
        name = path.stem.replace("delay_model_vs_baseline_", "")
        parts += [f"## Delay > 45 min: `{name}` vs P4 baselines\n",
                  "Best baseline = smoothed historical rate per origin x local departure hour x month. "
                  "Positive PR-AUC change = model better.\n", delay_table(path), ""]
    leak = OUT / "leakage_hub_state.csv"
    if leak.exists():
        lk = pd.read_csv(leak)
        parts += ["## Leakage check: hub-state features bucketed by scheduled hour\n",
                  "| feature | window | measure | n | unknown at issue time |", "|---|---|---|---|---|"]
        parts += [f"| {r.feature} | {r.window_min} min | {r.measure} | {r.n} | {r.unknown_share:.1%} |" for r in lk.itertuples()]
    (OUT / "test_set_summary.md").write_text("\n".join(parts) + "\n", encoding="utf-8")
    print("wrote", OUT / "test_set_summary.md")


if __name__ == "__main__":
    main()
